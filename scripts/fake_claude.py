"""Stands in for the `claude` command in tests, so they never call the real service.

Speaks the same stream-json format, with deltas cut in the middle of lines.
"""
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import marker_tools  # noqa: E402


def send(event):
    print(json.dumps(event), flush=True)


def delta(kind, field, text):
    send({"type": "stream_event", "event": {"type": "content_block_delta", "delta": {"type": kind, field: text}}})


def write(text):
    middle = len(text) // 2
    delta("text_delta", "text", text[:middle])
    delta("text_delta", "text", text[middle:])


def tool(name, **arguments):
    send({"type": "assistant", "message": {"content": [{"type": "tool_use", "name": name, "input": arguments}]}})


def main():
    assert sys.stdin.read()
    for flag in ("--strict-mcp-config", "--disable-slash-commands", "--setting-sources"):
        assert flag in sys.argv, flag
    lines = json.loads(Path("lines.json").read_text(encoding="utf-8"))
    assert Path("submission.pdf").is_file()
    system = Path("system.txt").read_text(encoding="utf-8")
    delta("thinking_delta", "thinking", "先看整体结构\n")
    tool("Read", file_path="C:/somewhere/submission.pdf")
    ran = Path("reference_1.py").is_file()
    if ran:  # the same tool the real agent gets, on the same file
        output = marker_tools.run_answer(".", "reference_1.py")
        send({"type": "assistant", "message": {"content": [{"type": "tool_use", "id": "run1",
              "name": "mcp__marker__run_answer", "input": {"file": "reference_1.py"}}]}})
        send({"type": "user", "message": {"content": [
            {"type": "tool_result", "tool_use_id": "run1", "content": [{"type": "text", "text": output}]}]}})
    marks = [
        ("tick", 1, None),
        ("cross", 3, "Check this sign."),
        ("circle", 5, "Say why this holds."),
        ("line", 7, None),
        ("arrow", 9, "Look here."),
        ("stamp", 9, "Not a tool on the toolbar."),
    ]
    for number, (kind, line, comment) in enumerate(marks, 1):
        write(f"正在看第 {number} 处\n")
        tool("mcp__marker__" + kind, page=0, line=lines[line]["line"], **({"comment": comment} if comment else {}))
        time.sleep(0.5)
    summary = "Generated by the test double." + (" Reference seen." if "reference_1" in system else "")
    summary += " Rules seen." if "The teacher's marking rules" in system else ""
    summary += " Output seen." if ran else ""
    write("SUMMARY " + summary)
    send({"type": "stream_event", "event": {"type": "content_block_stop"}})
    send({"type": "result", "is_error": False, "result": "done"})


if __name__ == "__main__":
    main()
